import { screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it } from 'vitest';
import { apiError, json } from '@/test/helpers';
import { renderApp } from '@/test/render';

const FINANCE = ['dashboard:view', 'wallets:read_all', 'deposits:read', 'deposits:approve', 'ledger:read', 'payouts:read', 'payouts:create', 'payouts:approve', 'reconciliation:run', 'refunds:issue'];
const finance = (routes: Record<string, () => Response>, fullName = 'Fina Finance') => renderApp({ path: '/finance', as: { fullName, roles: ['FINANCE_ADMIN'], permissions: FINANCE }, routes });

const deposit = (over: Record<string, unknown> = {}) => ({
  id: 'd-1',
  status: 'PENDING',
  amount: '100.0000',
  channel: 'BNCTL',
  referenceNo: 'TRF-77',
  hasProof: true,
  note: null,
  owner: { type: 'AGENT', id: 'a-1', name: 'Kios Colmera (AG-DIL-001)' },
  requestedBy: 'Maria Agente',
  reviewedBy: null,
  reviewedAt: null,
  rejectReason: null,
  createdAt: '2026-11-20T01:00:00.000Z',
  ...over,
});

describe('deposits', () => {
  it('approves a deposit with an idempotency key after a confirmation', async () => {
    const u = userEvent.setup();
    let status = 'PENDING';
    const { api } = finance({
      'GET /v1/deposits/requests': () => json([deposit({ status })]),
      'POST /v1/finance/deposits/d-1/approve': () => ((status = 'APPROVED'), json(deposit({ status }))),
    });
    expect(await screen.findByText('Kios Colmera (AG-DIL-001)')).toBeInTheDocument();
    await u.click(screen.getByRole('button', { name: 'Approve' }));
    const dialog = await screen.findByRole('dialog');
    expect(within(dialog).getByText(/Credit \$100.00 to the deposit wallet/)).toBeInTheDocument();
    await u.click(within(dialog).getByRole('button', { name: 'Approve' }));
    expect(await screen.findByText('Deposit approved and credited.')).toBeInTheDocument();
    const call = api.find('POST', '/v1/finance/deposits/d-1/approve')[0]!;
    expect(call.init.headers['Idempotency-Key']).toMatch(/\S{8,}/);
  });

  it('will not offer Approve on a request the signed-in person submitted (four-eyes)', async () => {
    finance({ 'GET /v1/deposits/requests': () => json([deposit({ requestedBy: 'Fina Finance' })]) });
    const btn = await screen.findByRole('button', { name: 'Approve' });
    expect(btn).toBeDisabled();
  });

  it('shows the server refusal if the maker-checker rule triggers anyway', async () => {
    const u = userEvent.setup();
    finance({
      'GET /v1/deposits/requests': () => json([deposit()]),
      'POST /v1/finance/deposits/d-1/approve': () => apiError(403, 'self_approval_forbidden', 'You cannot approve a request you submitted.'),
    });
    await u.click(await screen.findByRole('button', { name: 'Approve' }));
    await u.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Approve' }));
    expect(await screen.findByText('You cannot approve a request you submitted.')).toBeInTheDocument();
  });

  it('requires a reason to reject', async () => {
    const u = userEvent.setup();
    const { api } = finance({
      'GET /v1/deposits/requests': () => json([deposit()]),
      'POST /v1/finance/deposits/d-1/reject': () => json(deposit({ status: 'REJECTED' })),
    });
    await u.click(await screen.findByRole('button', { name: 'Reject' }));
    const dialog = await screen.findByRole('dialog');
    const confirm = within(dialog).getByRole('button', { name: 'Reject' });
    expect(confirm).toBeDisabled();
    await u.type(within(dialog).getByLabelText('Reason for rejecting'), 'Slip is unreadable');
    await u.click(confirm);
    await waitFor(() => expect(api.find('POST', '/v1/finance/deposits/d-1/reject')[0]!.body).toEqual({ reason: 'Slip is unreadable' }));
  });
});

const payout = (over: Record<string, unknown> = {}) => ({
  id: 'p-1',
  payoutNo: 'PO-261121-0001',
  status: 'PENDING_APPROVAL',
  fleetPartner: { id: 'f-1', companyName: 'Transporte Lorosae Express' },
  period: { start: '2026-11-14T15:00:00.000Z', end: '2026-11-21T15:00:00.000Z' },
  gross: '200.0000',
  claimDeduction: '20.0000',
  net: '180.0000',
  channel: 'BNCTL',
  bankReference: null,
  lineCount: 12,
  autoGenerated: false,
  createdBy: 'Fina Finance',
  approvedBy: null,
  approvedAt: null,
  paidAt: null,
  failureReason: null,
  createdAt: '2026-11-21T01:00:00.000Z',
  ...over,
});

describe('fleet payouts', () => {
  const open = async (u: ReturnType<typeof userEvent.setup>) => u.click(await screen.findByRole('tab', { name: 'Fleet payouts' }));

  it('does not let the preparer approve their own payout', async () => {
    const u = userEvent.setup();
    finance({ 'GET /v1/deposits/requests': () => json([]), 'GET /v1/finance/payouts': () => json([payout()]) });
    await open(u);
    expect(await screen.findByText('PO-261121-0001')).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Approve' })).toBeDisabled();
  });

  it('another finance admin approves it', async () => {
    const u = userEvent.setup();
    const { api } = finance(
      { 'GET /v1/deposits/requests': () => json([]), 'GET /v1/finance/payouts': () => json([payout()]), 'POST /v1/finance/payouts/p-1/approve': () => json(payout({ status: 'APPROVED' })) },
      'Carlos Second',
    );
    await open(u);
    await u.click(await screen.findByRole('button', { name: 'Approve' }));
    await u.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Approve' }));
    expect(await screen.findByText('Approved.')).toBeInTheDocument();
    expect(api.find('POST', '/v1/finance/payouts/p-1/approve')).toHaveLength(1);
  });

  it('marks an approved payout paid only with a bank reference, using an idempotency key', async () => {
    const u = userEvent.setup();
    const { api } = finance({
      'GET /v1/deposits/requests': () => json([]),
      'GET /v1/finance/payouts': () => json([payout({ status: 'APPROVED', approvedBy: 'Carlos Second' })]),
      'POST /v1/finance/payouts/p-1/pay': () => json(payout({ status: 'PAID' })),
    });
    await open(u);
    await u.click(await screen.findByRole('button', { name: 'Mark as paid' }));
    const dialog = await screen.findByRole('dialog');
    const confirm = within(dialog).getByRole('button', { name: 'Mark as paid' });
    expect(confirm).toBeDisabled();
    await u.type(within(dialog).getByLabelText('Bank transfer reference'), 'BNCTL-99812');
    await u.click(confirm);
    expect(await screen.findByText('Payout recorded as paid.')).toBeInTheDocument();
    const call = api.find('POST', '/v1/finance/payouts/p-1/pay')[0]!;
    expect(call.body).toEqual({ bankReference: 'BNCTL-99812' });
    expect(call.init.headers['Idempotency-Key']).toBeTruthy();
  });

  it('shows bank details only after an explicit, warned click', async () => {
    const u = userEvent.setup();
    const { api } = finance({
      'GET /v1/deposits/requests': () => json([]),
      'GET /v1/finance/payouts': () => json([payout({ status: 'APPROVED' })]),
      'GET /v1/finance/fleet-partners/f-1/bank-details': () => json({ bank: 'BNCTL', accountName: 'Transporte Lorosae', accountNo: '0012345678' }),
    });
    await open(u);
    await u.click(await screen.findByRole('button', { name: 'Bank details' }));
    const dialog = await screen.findByRole('dialog');
    expect(within(dialog).getByText(/recorded in the audit log/)).toBeInTheDocument();
    expect(within(dialog).queryByText('0012345678')).not.toBeInTheDocument();
    expect(api.find('GET', '/v1/finance/fleet-partners')).toHaveLength(0); // nothing was fetched yet
    await u.click(within(dialog).getByRole('button', { name: 'Show account number' }));
    expect(await within(dialog).findByText('0012345678')).toBeInTheDocument();
  });

  it('hides actions the role does not hold (read-only payout viewer)', async () => {
    const u = userEvent.setup();
    renderApp({
      path: '/finance',
      as: { roles: ['X'], permissions: ['deposits:read', 'payouts:read'] },
      routes: { 'GET /v1/deposits/requests': () => json([]), 'GET /v1/finance/payouts': () => json([payout({ status: 'APPROVED' })]) },
    });
    await u.click(await screen.findByRole('tab', { name: 'Fleet payouts' }));
    await screen.findByText('PO-261121-0001');
    for (const name of ['Approve', 'Mark as paid', 'Bank details', 'Generate payouts']) expect(screen.queryByRole('button', { name })).not.toBeInTheDocument();
  });
});

describe('refunds and reconciliation', () => {
  it('refunds with an idempotency key after confirmation', async () => {
    const u = userEvent.setup();
    const { api } = finance({
      'GET /v1/deposits/requests': () => json([]),
      'GET /v1/finance/reconciliation': () =>
        json({ ok: true, ledger: { ok: true, globalNet: '0.0000', mismatchedWallets: [], unbalancedTransactions: [] }, pendingSettlement: { wallet: '0.0000', expectedFromSettlements: '0.0000', ok: true }, escrow: { claimReserve: '170.0000', insurancePool: '40.0000', approvedUnpaidClaims: '0.0000' }, lowFloatAgents: [] }),
      'POST /v1/finance/refunds': () => json({ waybill: '670S-DIL-BCU-261121-000001', refunded: { usd: '2.5000' } }),
    });
    await u.click(await screen.findByRole('tab', { name: 'Reconciliation & refunds' }));
    expect(await screen.findByText('Everything balances.')).toBeInTheDocument();
    await u.type(screen.getByLabelText('Waybill'), '670s-dil-bcu-261121-000001');
    await u.type(screen.getByLabelText('Reason'), 'Collected at the kiosk');
    await u.click(screen.getByRole('button', { name: 'Refund add-on' }));
    await u.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Refund add-on' }));
    expect(await screen.findByText('Refunded $2.50 for 670S-DIL-BCU-261121-000001.')).toBeInTheDocument();
    const call = api.find('POST', '/v1/finance/refunds')[0]!;
    expect(call.body).toEqual({ waybill: '670S-DIL-BCU-261121-000001', reason: 'Collected at the kiosk' });
    expect(call.init.headers['Idempotency-Key']).toBeTruthy();
  });

  it('warns loudly when the ledger does not balance', async () => {
    const u = userEvent.setup();
    finance({
      'GET /v1/deposits/requests': () => json([]),
      'GET /v1/finance/reconciliation': () =>
        json({ ok: false, ledger: { ok: false, globalNet: '1.0000', mismatchedWallets: [{ walletId: 'w-9', balance: '5.0000', ledger: '4.0000' }], unbalancedTransactions: [] }, pendingSettlement: { wallet: '0.0000', expectedFromSettlements: '0.0000', ok: true }, escrow: { claimReserve: '0.0000', insurancePool: '0.0000', approvedUnpaidClaims: '0.0000' }, lowFloatAgents: [] }),
    });
    await u.click(await screen.findByRole('tab', { name: 'Reconciliation & refunds' }));
    expect(await screen.findByText(/Something does not balance/)).toBeInTheDocument();
    expect(screen.getByText(/w-9/)).toBeInTheDocument();
  });
});
