import { randomUUID } from 'node:crypto';
import { LedgerService } from '../src/ledger/ledger.service';
import { PayoutsService } from '../src/admin/payouts.service';
import { bearer, createTestApp, type TestCtx } from './helpers';
import { createNetwork, fund, sysWallet, walletBalance, type Network } from './scenario';
import { arrivedParcels, cs, finance, ops } from './admin-helpers';

const num = (v: string | number) => Number(v);

describe('Fleet payouts: batches, maker-checker, claim deductions, statements, schedule', () => {
  let ctx: TestCtx;
  let ledger: LedgerService;
  beforeAll(async () => {
    ctx = await createTestApp();
    ledger = ctx.app.get(LedgerService);
    await fund(ctx, sysWallet('CLAIM_ESCROW_RESERVE'), '1000.0000');
  });
  afterAll(() => ctx.close());

  const generate = (token: string, body: object, key: string = randomUUID()) => ctx.http.post('/v1/finance/payouts/generate').set(bearer(token)).set('Idempotency-Key', key).send(body);
  const post = (token: string, path: string, body: object = {}) => ctx.http.post(path).set(bearer(token)).send(body);
  const ownerToken = async (n: Network) => (await ctx.http.post('/v1/auth/login').send({ email: n.fleet.owner.email, password: n.fleet.owner.password })).body.accessToken as string;

  /** A fleet that has carried `count` parcels to the kiosk (fleet share released: $1.60 each). */
  async function fleetWithEarnings(count: number) {
    const n = await createNetwork(ctx);
    const { parcels } = await arrivedParcels(ctx, n, count);
    return { n, parcels };
  }

  /** Approved + paid claim against the fleet. */
  async function paidFleetClaim(n: Network, parcel: { waybill: string }, amount: string) {
    const desk = await cs(ctx);
    const fin = await finance(ctx);
    const c = (await ctx.http.post('/v1/claims').set(bearer(n.bcu.token)).set('Idempotency-Key', randomUUID()).send({ waybill: parcel.waybill, claimType: 'DAMAGED', requestedAmountUsd: amount })).body;
    await ctx.http.post(`/v1/claims/${c.id}/decision`).set(bearer(desk.token)).send({ decision: 'APPROVE', approvedAmountUsd: amount, liableParty: 'FLEET_PARTNER' });
    const paid = await ctx.http.post(`/v1/claims/${c.id}/pay`).set(bearer(fin.token)).send({ reference: 'CASH-F-1' });
    expect(paid.body.status).toBe('PAID');
    return c.id as string;
  }

  /* ---------------------------------------------- generation ---------------------------------------------- */
  describe('generation', () => {
    it('collects every released share once: 3 parcels → $4.80, each parcel is on exactly one payout', async () => {
      const { n } = await fleetWithEarnings(3);
      const fin = await finance(ctx);
      const r = await generate(fin.token, { fleetPartnerId: n.fleet.partnerId });
      expect(r.status).toBe(200);
      expect(r.body).toHaveLength(1);
      expect(r.body[0]).toMatchObject({ status: 'DRAFT', gross: '4.8000', claimDeduction: '0.0000', net: '4.8000', lineCount: 3, channel: 'BNCTL', autoGenerated: false });
      expect(r.body[0].payoutNo).toMatch(/^PO-\d{6}-\d{4}$/);

      const again = await generate(fin.token, { fleetPartnerId: n.fleet.partnerId });
      expect(again.status).toBe(422);
      expect(again.body.code).toBe('payout_empty'); // nothing left to pay

      const stmt = await ctx.http.get(`/v1/finance/payouts/${r.body[0].id}/statement`).set(bearer(fin.token));
      expect(stmt.body.lines).toHaveLength(3);
      expect(stmt.body.lines[0]).toMatchObject({ kind: 'EARNING', route: 'Díli → Baucau', canal: 'BUS_BAGGAGE', amount: '1.6000' });
      expect(stmt.body.totals).toEqual({ gross: '4.8000', claimDeduction: '0.0000', net: '4.8000' });
    });

    it('a retried request returns the same batch; parcels still waiting for arrival are NOT included', async () => {
      const n = await createNetwork(ctx);
      const { shipInTransit } = await import('./scenario');
      await shipInTransit(ctx, n, 2); // handed to the fleet but not arrived: share still pending
      const fin = await finance(ctx);
      expect((await generate(fin.token, { fleetPartnerId: n.fleet.partnerId })).body.code).toBe('payout_empty');

      const { n: m } = await fleetWithEarnings(1);
      const key = randomUUID();
      const a = await generate(fin.token, { fleetPartnerId: m.fleet.partnerId }, key);
      const b = await generate(fin.token, { fleetPartnerId: m.fleet.partnerId }, key);
      expect(b.body[0].id).toBe(a.body[0].id);
      expect(b.headers['idempotent-replayed']).toBe('true');
    });

    it('3 simultaneous generations produce ONE payout; no parcel can be paid out twice', async () => {
      const { n } = await fleetWithEarnings(4);
      const clerks = await Promise.all([finance(ctx), finance(ctx), finance(ctx)]);
      const results = await Promise.all(clerks.map((c) => generate(c.token, { fleetPartnerId: n.fleet.partnerId })));
      const created = results.filter((r) => r.status === 200);
      expect(created).toHaveLength(1);
      expect(created[0]!.body[0].gross).toBe('6.4000');
      for (const r of results.filter((x) => x.status !== 200)) expect([409, 422]).toContain(r.status);
      const items = await ctx.prisma.fleetPayoutItem.count({ where: { payout: { fleetPartnerId: n.fleet.partnerId }, kind: 'EARNING' } });
      expect(items).toBe(4);
    });

    it('validates input and permissions', async () => {
      const fin = await finance(ctx);
      expect((await generate(fin.token, {})).status).toBe(422); // partner or cycle required
      expect((await generate(fin.token, { fleetPartnerId: randomUUID() })).status).toBe(404);
      expect((await generate(fin.token, { cycle: 'DAILY', periodStart: '2026-11-02T00:00:00.000Z', periodEnd: '2026-11-01T00:00:00.000Z' })).status).toBe(422);
      expect((await generate((await ops(ctx)).token, { cycle: 'DAILY' })).status).toBe(403);
      expect((await generate((await cs(ctx)).token, { cycle: 'DAILY' })).status).toBe(403);
    });
  });

  /* ------------------------------------------------ lifecycle ------------------------------------------------ */
  describe('lifecycle: draft → submitted → approved (a DIFFERENT person) → paid', () => {
    it('moves exactly the net out of FLEET_PAYABLE and stores the bank / MOSAN reference', async () => {
      const { n } = await fleetWithEarnings(3);
      const creator = await finance(ctx);
      const approver = await finance(ctx);
      const p = (await generate(creator.token, { fleetPartnerId: n.fleet.partnerId })).body[0];

      expect((await post(approver.token, `/v1/finance/payouts/${p.id}/approve`)).status).toBe(409); // not submitted yet
      expect((await post(creator.token, `/v1/finance/payouts/${p.id}/pay`, { bankReference: 'BNCTL-9001' })).status).toBe(409);
      expect((await post(creator.token, `/v1/finance/payouts/${p.id}/submit`)).body.status).toBe('PENDING_APPROVAL');

      const self = await post(creator.token, `/v1/finance/payouts/${p.id}/approve`);
      expect(self.status).toBe(403);
      expect(self.body.code).toBe('self_approval_forbidden');
      expect((await post(approver.token, `/v1/finance/payouts/${p.id}/approve`)).body).toMatchObject({ status: 'APPROVED', approvedBy: 'Test User' });

      const payableBefore = num(await walletBalance(ctx, n.fleet.payable));
      const clearingBefore = num(await walletBalance(ctx, sysWallet('EXTERNAL_CLEARING')));
      expect(payableBefore).toBeCloseTo(4.8, 4);
      const paid = await post(approver.token, `/v1/finance/payouts/${p.id}/pay`, { bankReference: 'BNCTL-9001' });
      expect(paid.status).toBe(200);
      expect(paid.body).toMatchObject({ status: 'PAID', bankReference: 'BNCTL-9001' });
      expect(num(await walletBalance(ctx, n.fleet.payable))).toBeCloseTo(0, 4);
      expect(num(await walletBalance(ctx, sysWallet('EXTERNAL_CLEARING'))) - clearingBefore).toBeCloseTo(4.8, 4);
      expect((await ctx.prisma.fleetPayout.findUniqueOrThrow({ where: { id: p.id } })).ledgerTxnId).not.toBeNull();

      expect((await post(approver.token, `/v1/finance/payouts/${p.id}/pay`, { bankReference: 'BNCTL-9001' })).status).toBe(409);
      expect((await post(approver.token, `/v1/finance/payouts/${p.id}/cancel`)).status).toBe(409); // paid is final
      expect(num(await walletBalance(ctx, n.fleet.payable))).toBeCloseTo(0, 4);
      expect((await ledger.reconcile()).ok).toBe(true);
    });

    it('a failed bank transfer can be retried; cancelling frees every parcel for the next batch', async () => {
      const { n } = await fleetWithEarnings(2);
      const a = await finance(ctx);
      const b = await finance(ctx);
      const p = (await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body[0];
      await post(a.token, `/v1/finance/payouts/${p.id}/submit`);
      await post(b.token, `/v1/finance/payouts/${p.id}/approve`);
      expect((await post(b.token, `/v1/finance/payouts/${p.id}/fail`, { reason: 'Beneficiary account closed' })).body).toMatchObject({ status: 'FAILED', failureReason: 'Beneficiary account closed' });
      expect(num(await walletBalance(ctx, n.fleet.payable))).toBeCloseTo(3.2, 4); // money untouched

      // while a failed batch is open its parcels are still locked
      expect((await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body.code).toBe('payout_empty');
      expect((await post(a.token, `/v1/finance/payouts/${p.id}/cancel`)).body.status).toBe('CANCELLED');
      const regen = await generate(a.token, { fleetPartnerId: n.fleet.partnerId });
      expect(regen.body[0]).toMatchObject({ gross: '3.2000', lineCount: 2 });

      // retry path: fail → pay again
      const p2 = regen.body[0];
      await post(a.token, `/v1/finance/payouts/${p2.id}/submit`);
      await post(b.token, `/v1/finance/payouts/${p2.id}/approve`);
      await post(b.token, `/v1/finance/payouts/${p2.id}/fail`, { reason: 'Network error' });
      expect((await post(b.token, `/v1/finance/payouts/${p2.id}/pay`, { bankReference: 'RETRY-OK-1' })).body.status).toBe('PAID');
      expect(num(await walletBalance(ctx, n.fleet.payable))).toBeCloseTo(0, 4);
    });

    it('only Finance can drive it (Ops and CS get 403)', async () => {
      const { n } = await fleetWithEarnings(1);
      const fin = await finance(ctx);
      const p = (await generate(fin.token, { fleetPartnerId: n.fleet.partnerId })).body[0];
      for (const who of [await ops(ctx), await cs(ctx)]) {
        for (const path of ['submit', 'approve', 'pay', 'cancel']) expect((await post(who.token, `/v1/finance/payouts/${p.id}/${path}`, { bankReference: 'x-123' })).status).toBe(403);
        expect((await ctx.http.get('/v1/finance/payouts').set(bearer(who.token))).status).toBe(403);
      }
    });
  });

  /* ------------------------------------------- claim deductions ------------------------------------------- */
  describe('claim deductions', () => {
    it('a claim the fleet was ruled liable for is netted off and returned to the reserve', async () => {
      const { n, parcels } = await fleetWithEarnings(3);
      const claimId = await paidFleetClaim(n, parcels[0]!, '2.00');
      const a = await finance(ctx);
      const b = await finance(ctx);
      const p = (await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body[0];
      expect(p).toMatchObject({ gross: '4.8000', claimDeduction: '2.0000', net: '2.8000', lineCount: 4 });
      const stmt = await ctx.http.get(`/v1/finance/payouts/${p.id}/statement`).set(bearer(a.token));
      expect(stmt.body.lines.filter((l: { kind: string }) => l.kind === 'CLAIM_DEDUCTION')).toEqual([expect.objectContaining({ amount: '-2.0000', description: expect.stringMatching(/^Claim CLM-/) })]);

      // the same claim cannot be deducted twice while this batch is open
      await post(a.token, `/v1/finance/payouts/${p.id}/submit`);
      await post(b.token, `/v1/finance/payouts/${p.id}/approve`);
      const escrowBefore = num(await walletBalance(ctx, sysWallet('CLAIM_ESCROW_RESERVE')));
      const clearingBefore = num(await walletBalance(ctx, sysWallet('EXTERNAL_CLEARING')));
      expect((await post(b.token, `/v1/finance/payouts/${p.id}/pay`, { bankReference: 'BNCTL-2' })).status).toBe(200);
      expect(num(await walletBalance(ctx, sysWallet('EXTERNAL_CLEARING'))) - clearingBefore).toBeCloseTo(2.8, 4);
      expect(num(await walletBalance(ctx, sysWallet('CLAIM_ESCROW_RESERVE'))) - escrowBefore).toBeCloseTo(2.0, 4);
      expect(num(await walletBalance(ctx, n.fleet.payable))).toBeCloseTo(0, 4);

      const claim = await ctx.http.get(`/v1/claims/${claimId}`).set(bearer(a.token));
      expect(claim.body.recovery).toMatchObject({ recovered: '2.0000', outstanding: '0.0000' });
      expect((await ledger.reconcile()).ok).toBe(true);
    });

    it('a deduction never exceeds the batch; the rest is carried to the next payout', async () => {
      const { n, parcels } = await fleetWithEarnings(2); // gross $3.20
      const claimId = await paidFleetClaim(n, parcels[0]!, '10.00');
      const a = await finance(ctx);
      const b = await finance(ctx);

      const first = (await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body[0];
      expect(first).toMatchObject({ gross: '3.2000', claimDeduction: '3.2000', net: '0.0000' });
      await post(a.token, `/v1/finance/payouts/${first.id}/submit`);
      await post(b.token, `/v1/finance/payouts/${first.id}/approve`);
      const clearingBefore = num(await walletBalance(ctx, sysWallet('EXTERNAL_CLEARING')));
      expect((await post(b.token, `/v1/finance/payouts/${first.id}/pay`, { bankReference: 'ZERO-NET-1' })).body.status).toBe('PAID'); // net 0 is a valid settlement
      expect(num(await walletBalance(ctx, sysWallet('EXTERNAL_CLEARING'))) - clearingBefore).toBeCloseTo(0, 4);
      expect((await ctx.http.get(`/v1/claims/${claimId}`).set(bearer(a.token))).body.recovery).toMatchObject({ recovered: '3.2000', outstanding: '6.8000' });

      // new earnings arrive later → the remaining $6.80 is taken from them
      await arrivedParcels(ctx, n, 5); // $8.00 more
      const second = (await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body[0];
      expect(second).toMatchObject({ gross: '8.0000', claimDeduction: '6.8000', net: '1.2000' });
    });

    it('cancelling a batch releases the claim for the next one', async () => {
      const { n, parcels } = await fleetWithEarnings(2);
      await paidFleetClaim(n, parcels[0]!, '1.00');
      const a = await finance(ctx);
      const p = (await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body[0];
      expect(p.claimDeduction).toBe('1.0000');
      await post(a.token, `/v1/finance/payouts/${p.id}/cancel`);
      expect((await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body[0].claimDeduction).toBe('1.0000');
    });
  });

  /* ----------------------------------------- fleet-owner portal ----------------------------------------- */
  describe('what the fleet owner sees', () => {
    it('own payouts (never drafts), statements as JSON / CSV, per-trip earnings — nobody else’s', async () => {
      const { n, parcels } = await fleetWithEarnings(2);
      const other = await fleetWithEarnings(1);
      const a = await finance(ctx);
      const b = await finance(ctx);
      const owner = await ownerToken(n);
      const otherOwner = await ownerToken(other.n);

      // before the first payout: earnings are RELEASED, no payouts visible
      const e0 = await ctx.http.get('/v1/fleet/earnings').set(bearer(owner));
      expect(e0.body).toHaveLength(2);
      expect(e0.body.every((x: { state: string; share: string }) => x.state === 'RELEASED' && x.share === '1.6000')).toBe(true);
      expect((await ctx.http.get('/v1/fleet/payouts').set(bearer(owner))).body).toEqual([]);

      const p = (await generate(a.token, { fleetPartnerId: n.fleet.partnerId })).body[0];
      expect((await ctx.http.get('/v1/fleet/payouts').set(bearer(owner))).body).toEqual([]); // DRAFT stays internal
      expect((await ctx.http.get(`/v1/fleet/payouts/${p.id}/statement`).set(bearer(owner))).status).toBe(404);
      await post(a.token, `/v1/finance/payouts/${p.id}/submit`);
      await post(b.token, `/v1/finance/payouts/${p.id}/approve`);
      await post(b.token, `/v1/finance/payouts/${p.id}/pay`, { bankReference: 'BNCTL-777' });

      const mine = await ctx.http.get('/v1/fleet/payouts').set(bearer(owner));
      expect(mine.body.map((x: { payoutNo: string }) => x.payoutNo)).toEqual([p.payoutNo]);
      expect(mine.body[0]).toMatchObject({ status: 'PAID', net: '3.2000' });
      expect((await ctx.http.get('/v1/fleet/payouts').set(bearer(otherOwner))).body).toEqual([]);
      expect((await ctx.http.get(`/v1/fleet/payouts/${p.id}/statement`).set(bearer(otherOwner))).status).toBe(404);

      const json = await ctx.http.get(`/v1/fleet/payouts/${p.id}/statement`).set(bearer(owner));
      expect(json.body).toMatchObject({ payoutNo: p.payoutNo, bankReference: 'BNCTL-777', totals: { net: '3.2000' } });
      const csv = await ctx.http.get(`/v1/fleet/payouts/${p.id}/statement?format=csv`).set(bearer(owner));
      expect(csv.headers['content-type']).toContain('text/csv');
      expect(csv.text.charCodeAt(0)).toBe(0xfeff); // BOM so Excel opens the UTF-8 (Díli) correctly
      expect(csv.text).toContain(parcels[0]!.waybill);
      expect(csv.text).toContain('Net payable,3.0000'.replace('3.0000', '3.2000'));

      const e1 = await ctx.http.get('/v1/fleet/earnings').set(bearer(owner));
      expect(e1.body.every((x: { state: string; payoutNo: string }) => x.state === 'PAID' && x.payoutNo === p.payoutNo)).toBe(true);
      expect((await ctx.http.get('/v1/fleet/earnings').set(bearer(otherOwner))).body).toHaveLength(1);
    });

    it('drivers see no money; Ops cannot read the owner portal', async () => {
      const { n } = await fleetWithEarnings(1);
      expect((await ctx.http.get('/v1/fleet/earnings').set(bearer(n.fleet.driver.token))).status).toBe(403);
      expect((await ctx.http.get('/v1/fleet/payouts').set(bearer(n.fleet.driver.token))).status).toBe(403);
      expect((await ctx.http.get('/v1/fleet/me').set(bearer(n.fleet.driver.token))).status).toBe(403);
      const me = await ctx.http.get('/v1/fleet/me').set(bearer(await ownerToken(n)));
      expect(me.body).toMatchObject({ payableBalance: '1.6000', vehicleCount: 3, driverCount: 1 });
      expect(me.body.bank).toBeUndefined();
    });
  });

  /* ------------------------------------------------ schedule ------------------------------------------------ */
  describe('scheduled drafts (06:00 Asia/Dili)', () => {
    it('creates DRAFTs owned by the system user, once per period; Finance still has to submit and approve', async () => {
      const { n } = await fleetWithEarnings(2);
      await ctx.prisma.fleetPartner.update({ where: { id: n.fleet.partnerId }, data: { payoutCycle: 'WEEKLY' } });
      // pretend the shares were released in the previous week
      await ctx.prisma.shipmentSettlement.updateMany({ where: { fleetPartnerId: n.fleet.partnerId }, data: { fleetReleasedAt: new Date(Date.now() - 10 * 86_400_000) } });

      const svc = ctx.app.get(PayoutsService);
      const created = await svc.generateDue('WEEKLY', new Date());
      const mine = await ctx.prisma.fleetPayout.findMany({ where: { fleetPartnerId: n.fleet.partnerId } });
      expect(mine).toHaveLength(1);
      expect(created).toContain(mine[0]!.id);
      expect(mine[0]).toMatchObject({ status: 'DRAFT', autoGenerated: true });
      expect(mine[0]!.grossAmountUsd.toFixed(4)).toBe('3.2000');
      const creator = await ctx.prisma.user.findUniqueOrThrow({ where: { id: mine[0]!.createdBy } });
      expect(creator.email).toBe('system@670send.internal');
      expect(creator.isActive).toBe(false); // the technical user cannot log in

      expect(await svc.generateDue('WEEKLY', new Date())).toEqual([]); // a second run changes nothing
      expect(await ctx.prisma.fleetPayout.count({ where: { fleetPartnerId: n.fleet.partnerId } })).toBe(1);

      // any human Finance user can approve it (creator ≠ approver)
      const fin = await finance(ctx);
      expect((await post(fin.token, `/v1/finance/payouts/${mine[0]!.id}/submit`)).status).toBe(200);
      expect((await post((await finance(ctx)).token, `/v1/finance/payouts/${mine[0]!.id}/approve`)).body.status).toBe('APPROVED');
    });

    it('DAILY partners are not touched by a WEEKLY run', async () => {
      const { n } = await fleetWithEarnings(1);
      await ctx.prisma.fleetPartner.update({ where: { id: n.fleet.partnerId }, data: { payoutCycle: 'DAILY' } });
      await ctx.prisma.shipmentSettlement.updateMany({ where: { fleetPartnerId: n.fleet.partnerId }, data: { fleetReleasedAt: new Date(Date.now() - 2 * 86_400_000) } });
      const svc = ctx.app.get(PayoutsService);
      await svc.generateDue('WEEKLY', new Date());
      expect(await ctx.prisma.fleetPayout.count({ where: { fleetPartnerId: n.fleet.partnerId } })).toBe(0);
      await svc.generateDue('DAILY', new Date());
      expect(await ctx.prisma.fleetPayout.count({ where: { fleetPartnerId: n.fleet.partnerId } })).toBe(1);
    });
  });
});
